export const STORAGE_KEY_CATALOG = 'netsuite_parts_catalog_data_v2';
export const STORAGE_KEY_META = 'netsuite_parts_catalog_metadata_v2';

export function loadPersistedCatalog(): { catalog: PartItem[]; isCustom: boolean; lastUpdated?: string; sourceDescription?: string } {
  try {
    const rawData = localStorage.getItem(STORAGE_KEY_CATALOG);
    const rawMeta = localStorage.getItem(STORAGE_KEY_META);
    if (rawData) {
      const parsed = JSON.parse(rawData);
      if (Array.isArray(parsed) && parsed.length > 0) {
        let meta = { isCustom: true, lastUpdated: new Date().toISOString(), sourceDescription: 'Imported Database' };
        if (rawMeta) {
          try {
            meta = JSON.parse(rawMeta);
          } catch (e) {
            // ignore
          }
        }
        return {
          catalog: parsed,
          isCustom: meta.isCustom,
          lastUpdated: meta.lastUpdated,
          sourceDescription: meta.sourceDescription
        };
      }
    }
  } catch (err) {
    console.error('Error loading stored catalog:', err);
  }
  return {
    catalog: DEFAULT_PARTS_CATALOG,
    isCustom: false,
    lastUpdated: undefined,
    sourceDescription: 'Default System Catalog'
  };
}

export function savePersistedCatalog(items: PartItem[], isCustom: boolean = true, description?: string): void {
  try {
    localStorage.setItem(STORAGE_KEY_CATALOG, JSON.stringify(items));
    localStorage.setItem(
      STORAGE_KEY_META,
      JSON.stringify({
        isCustom,
        itemCount: items.length,
        lastUpdated: new Date().toISOString(),
        sourceDescription: description || (isCustom ? 'Imported / User-Updated Database' : 'Default System Catalog')
      })
    );
  } catch (err) {
    console.error('Error persisting catalog to localStorage:', err);
  }
}

export function resetPersistedCatalog(): PartItem[] {
  try {
    localStorage.removeItem(STORAGE_KEY_CATALOG);
    localStorage.removeItem(STORAGE_KEY_META);
  } catch (err) {
    console.error('Error clearing persisted catalog:', err);
  }
  return DEFAULT_PARTS_CATALOG;
}

export function parseCatalogFileContent(content: string): { items: PartItem[]; headersFound?: string[]; totalParsed: number } {
  const lines = content.split(/\r?\n/).map(l => l.trim()).filter(l => l.length > 0);
  if (lines.length === 0) return { items: [], totalParsed: 0 };

  const parsedItems: PartItem[] = [];
  const seenMap = new Map<string, PartItem>();

  // Helper to split row handling commas inside quotes or tabs
  const splitRow = (line: string): string[] => {
    if (line.includes('\t')) {
      return line.split('\t').map(c => c.trim().replace(/^"|"$/g, ''));
    }
    // simple CSV split considering quotes
    const results: string[] = [];
    let current = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"' && (i === 0 || line[i - 1] !== '\\')) {
        inQuotes = !inQuotes;
      } else if (char === ',' && !inQuotes) {
        results.push(current.trim().replace(/^"|"$/g, '').replace(/""/g, '"'));
        current = '';
      } else {
        current += char;
      }
    }
    results.push(current.trim().replace(/^"|"$/g, '').replace(/""/g, '"'));
    return results;
  };

  let headerIndices: { idIdx: number; nameIdx: number; classIdx: number; typeIdx: number } | null = null;
  let startIndex = 0;

  // Check first row for header names
  const firstRow = splitRow(lines[0]);
  const lowerCols = firstRow.map(c => c.toLowerCase().replace(/[^a-z0-9]/g, ''));

  const idCol = lowerCols.findIndex(c => c.includes('internalid') || c === 'id' || c.includes('itemid') || c.includes('internal'));
  const nameCol = lowerCols.findIndex(c => c.includes('partnumber') || c.includes('itemname') || c.includes('partno') || c === 'name' || c === 'item' || c.includes('itemnumber') || c.includes('displayname'));
  const classCol = lowerCols.findIndex(c => c === 'class' || c.includes('category') || c.includes('department'));
  const typeCol = lowerCols.findIndex(c => c === 'type' || c.includes('itemtype'));

  if (idCol !== -1 || nameCol !== -1) {
    headerIndices = {
      idIdx: idCol !== -1 ? idCol : 0,
      nameIdx: nameCol !== -1 ? nameCol : 1,
      classIdx: classCol,
      typeIdx: typeCol
    };
    startIndex = 1;
  }

  for (let i = startIndex; i < lines.length; i++) {
    const cols = splitRow(lines[i]);
    if (cols.length < 2) continue;

    let internalId = '';
    let partNumber = '';
    let itemClass = 'COMPONENTS';
    let itemType = 'Assembly/Bill of Materials';

    if (headerIndices) {
      internalId = cols[headerIndices.idIdx] || '';
      partNumber = cols[headerIndices.nameIdx] || '';
      if (headerIndices.classIdx !== -1 && cols[headerIndices.classIdx]) {
        itemClass = cols[headerIndices.classIdx];
      }
      if (headerIndices.typeIdx !== -1 && cols[headerIndices.typeIdx]) {
        itemType = cols[headerIndices.typeIdx];
      }
    } else {
      // Standard NetSuite export column positions: Internal ID, Type, Class, Name/Number
      if (cols.length >= 4 && /^\d+$/.test(cols[0])) {
        internalId = cols[0];
        itemType = cols[1] || itemType;
        itemClass = cols[2] || itemClass;
        partNumber = cols[3];
      } else if (/^\d+$/.test(cols[0])) {
        // [InternalId, PartNumber, Class?, Type?]
        internalId = cols[0];
        partNumber = cols[1];
        if (cols[2]) itemClass = cols[2];
        if (cols[3]) itemType = cols[3];
      } else if (/^\d+$/.test(cols[1])) {
        // [PartNumber, InternalId, Class?, Type?]
        partNumber = cols[0];
        internalId = cols[1];
        if (cols[2]) itemClass = cols[2];
        if (cols[3]) itemType = cols[3];
      } else {
        // Fallback: assume col 0 is part number, col 1 is internal id
        partNumber = cols[0];
        internalId = cols[1];
      }
    }

    if (internalId && partNumber && internalId.toLowerCase() !== 'internal id' && partNumber.toLowerCase() !== 'item name') {
      const cleanPart = partNumber.trim();
      const cleanId = internalId.trim();
      if (cleanPart && cleanId) {
        seenMap.set(cleanPart.toUpperCase(), {
          internalId: cleanId,
          partNumber: cleanPart,
          class: itemClass.trim(),
          type: itemType.trim()
        });
      }
    }
  }

  const items = Array.from(seenMap.values());
  return { items, totalParsed: items.length };
}

export function exportCatalogToCsv(items: PartItem[]): string {
  const lines = ['Internal ID,Type,Class,Item Name/Number'];
  items.forEach(item => {
    const escapeCsv = (str: string = '') => {
      if (str.includes(',') || str.includes('"') || str.includes('\n')) {
        return `"${str.replace(/"/g, '""')}"`;
      }
      return str;
    };
    lines.push([
      escapeCsv(item.internalId),
      escapeCsv(item.type || 'Assembly/Bill of Materials'),
      escapeCsv(item.class || 'COMPONENTS'),
      escapeCsv(item.partNumber)
    ].join(','));
  });
  return lines.join('\n');
}

export function lookupPart(partNumber: string, catalog: PartItem[] = DEFAULT_PARTS_CATALOG): PartItem | undefined {
  if (!partNumber) return undefined;
  const clean = partNumber.trim().toUpperCase();
  // Exact match
  let found = catalog.find(item => item.partNumber.trim().toUpperCase() === clean);
  if (found) return found;

  // Match without SHUN_ prefix if user searched without it or vice versa
  if (clean.startsWith('SHUN_')) {
    const withoutShun = clean.substring(5);
    found = catalog.find(item => item.partNumber.trim().toUpperCase() === withoutShun);
    if (found) return found;
  } else {
    const withShun = `SHUN_${clean}`;
    found = catalog.find(item => item.partNumber.trim().toUpperCase() === withShun);
    if (found) return found;
  }

  // Check if user entered internal ID directly
  found = catalog.find(item => item.internalId.trim() === clean);
  return found;
}

